def guard_overrides(
    settings: ModelSettings, catalog_path: Path
) -> list[tuple[str, str]]:
    """Highest-precedence guards, including settings a project config could override."""

    compact_limit = max(8192, int(settings.context_window * 0.90))
    history = "save-all" if settings.persist_history else "none"
    false_keys = (
        "analytics.enabled",
        "feedback.enabled",
        "memories.generate_memories",
        "memories.use_memories",
        "agents.enabled",
        "features.apps",
        "features.browser_use",
        "features.browser_use_external",
        "features.computer_use",
        "features.fast_mode",
        "features.guardian_approval",
        "features.image_generation",
        "features.in_app_browser",
        "features.in_app_updates",
        "features.memories",
        "features.multi_agent",
        "features.multi_agent_v2",
        "features.plugin_sharing",
        "features.plugins",
        "features.remote_compaction_v2",
        "features.remote_plugin",
        "features.standalone_web_search",
        "features.tool_suggest",
        "tools.web_search",
        "apps._default.enabled",
    )
    overrides: list[tuple[str, str]] = [
        ("model", toml_string(settings.slug)),
        ("review_model", toml_string(settings.slug)),
        ("model_provider", '"modal"'),
        ("model_catalog_json", toml_string(catalog_path)),
        ("model_context_window", str(settings.context_window)),
        ("model_auto_compact_token_limit", str(compact_limit)),
        ("model_reasoning_effort", toml_string(settings.reasoning_effort)),
        ("model_reasoning_summary", '"none"'),
        ("web_search", '"disabled"'),
        ("check_for_update_on_startup", "false"),
        ("approvals_reviewer", '"user"'),
        ("apps._default.approvals_reviewer", '"user"'),
        ("history.persistence", toml_string(history)),
        ("agents.default_subagent_model", toml_string(settings.slug)),
        ("otel.exporter", '"none"'),
        ("otel.metrics_exporter", '"none"'),
        ("otel.trace_exporter", '"none"'),
        ("otel.log_user_prompt", "false"),
    ]
    overrides.extend((key, "false") for key in false_keys)
    return overrides


def _strict_offline_probe(configuration: RunConfiguration) -> None:
    """Make strict parsing reach a guaranteed-local connection failure, never a model."""

    guard_socket = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    guard_socket.bind(("127.0.0.1", 0))
    port = int(guard_socket.getsockname()[1])
    local_base = f"http://127.0.0.1:{port}/v1"
    probe_environment = configuration.environment.copy()
    probe_environment["MODAL_PROXY_TOKEN"] = "wk-offline-probe.ws-offline-probe"
    command = configuration.command_prefix() + [
        "-c",
        f"model_providers.modal.base_url={toml_string(local_base)}",
        "-c",
        "model_providers.modal.request_max_retries=0",
        "-c",
        "model_providers.modal.stream_max_retries=0",
        "exec",
        "--ephemeral",
        "--skip-git-repo-check",
        "--ignore-rules",
        "--json",
        "codex-modal offline strict configuration probe",
    ]
    try:
        result = subprocess.run(
            command,
            cwd=PROJECT_ROOT,
            env=probe_environment,
            stdin=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            errors="replace",
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=30,
            check=False,
        )
    finally:
        guard_socket.close()
    combined = f"{result.stderr}\n{result.stdout}"
    if local_base in combined and "error" in combined.lower():
        return
    detail = combined.strip()
    raise RuntimeError(
        "Codex strict-mode validation did not reach the expected closed localhost provider"
        + (f": {detail}" if detail else ".")
    )


def _validate(
    configuration: RunConfiguration, workspace: Path, *, validate_strict: bool
) -> None:
    catalog_document = _run_json(
        [
            configuration.codex_executable,
            "-c",
            f"model_catalog_json={toml_string(configuration.catalog_path)}",
            "debug",
            "models",
        ],
        environment=configuration.environment,
    )
    models = catalog_document.get("models")
    slugs = [
        str(model.get("slug"))
        for model in models or []
        if isinstance(model, dict) and model.get("slug")
    ]
    if slugs != [configuration.settings.slug]:
        raise RuntimeError(
            "Codex did not enforce the generated one-model catalog; loaded: "
            + (", ".join(slugs) if slugs else "<none>")
        )

    validation_prefix = configuration.command_prefix(strict=False)
    validation = subprocess.run(
        validation_prefix + ["debug", "prompt-input", "codex-modal configuration validation"],
        cwd=workspace,
        env=configuration.environment,
        text=True,
        encoding="utf-8",
        errors="replace",
        stdout=subprocess.DEVNULL,
        stderr=subprocess.PIPE,
        timeout=60,
        check=False,
    )
    if validation.returncode != 0:
        detail = validation.stderr.strip()
        raise RuntimeError(
            "The installed Codex CLI rejected the generated Modal-only profile"
            + (f": {detail}" if detail else ".")
        )
    if validate_strict:
        _strict_offline_probe(configuration)


def _prune_old_ephemeral_files() -> None:
    import time

    threshold = time.time() - 24 * 60 * 60
    for pattern in ("modal_*.config.toml", "catalog-modal_*.json"):
        for path in CODEX_HOME.glob(pattern):
            try:
                if path.stat().st_mtime < threshold:
                    path.unlink()
            except OSError:
                pass


def prepare_run_configuration(
    settings: ModelSettings,
    *,
    workspace: Path,
    proxy_token: str | None,
    validate_strict: bool = True,
) -> RunConfiguration:
    ensure_state_dirs()
    _atomic_text(CODEX_HOME / "config.toml", BASE_CONFIG)
    _prune_old_ephemeral_files()
    codex_executable = find_codex()
    environment = isolated_environment(proxy_token)
    template = _bundled_template(codex_executable, environment)

    run_id = f"modal_{os.getpid()}_{secrets.token_hex(6)}"
    catalog_path = CODEX_HOME / f"catalog-{run_id}.json"
    profile_name = run_id
    profile_path = CODEX_HOME / f"{profile_name}.config.toml"
    catalog = {"models": [_model_entry(template, settings)]}
    _atomic_text(
        catalog_path,
        json.dumps(catalog, ensure_ascii=False, indent=2) + "\n",
    )
    _atomic_text(profile_path, _profile_text(settings, catalog_path, workspace))

    configuration = RunConfiguration(
        codex_executable=codex_executable,
        profile_name=profile_name,
        profile_path=profile_path,
        catalog_path=catalog_path,
        settings=settings,
        environment=environment,
    )
    try:
        _validate(configuration, workspace, validate_strict=validate_strict)
    except Exception:
        configuration.clean_up()
        raise
    return configuration
