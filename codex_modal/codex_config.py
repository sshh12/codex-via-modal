@dataclass(frozen=True)
class ModelSettings:
    slug: str
    display_model: str
    context_window: int
    reasoning_effort: str
    reasoning_levels: tuple[str, ...]
    provider_base_url: str
    persist_history: bool


@dataclass
class RunConfiguration:
    codex_executable: str
    profile_name: str
    profile_path: Path
    catalog_path: Path
    settings: ModelSettings
    environment: dict[str, str]

    def command_prefix(
        self, *, strict: bool = True, include_profile: bool = True
    ) -> list[str]:
        arguments = [self.codex_executable]
        if include_profile:
            arguments.extend(["--profile", self.profile_name])
        if strict:
            arguments.append("--strict-config")
        arguments.extend(["--model", self.settings.slug])
        for key, value in guard_overrides(self.settings, self.catalog_path):
            arguments.extend(["-c", f"{key}={value}"])
        return arguments

    def clean_up(self) -> None:
        for path in (self.profile_path, self.catalog_path):
            try:
                path.unlink()
            except FileNotFoundError:
                pass


def toml_string(value: str | Path) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def _atomic_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.{secrets.token_hex(4)}.tmp")
    temporary.write_text(content, encoding="utf-8", newline="\n")
    os.replace(temporary, path)


def find_codex() -> str:
    executable = shutil.which("codex")
    if not executable:
        raise RuntimeError("Codex CLI is not installed or is not on PATH.")
    return executable


def isolated_environment(proxy_token: str | None = None) -> dict[str, str]:
    environment = os.environ.copy()
    for key in list(environment):
        upper = key.upper()
        if upper in {
            "OPENAI_API_KEY",
            "OPENAI_BASE_URL",
            "OPENAI_ORG_ID",
            "OPENAI_ORGANIZATION",
            "CODEX_API_KEY",
            "CODEX_SQLITE_HOME",
            "MODAL_PROXY_TOKEN_ID",
            "MODAL_PROXY_TOKEN_SECRET",
            "MODAL_TOKEN_ID",
            "MODAL_TOKEN_SECRET",
            "HF_TOKEN",
            "HUGGING_FACE_HUB_TOKEN",
        }:
            environment.pop(key, None)
    environment["CODEX_HOME"] = str(CODEX_HOME)
    if proxy_token is None:
        environment.pop("MODAL_PROXY_TOKEN", None)
    else:
        environment["MODAL_PROXY_TOKEN"] = proxy_token
    return environment


def _run_json(
    arguments: list[str],
    *,
    environment: dict[str, str],
    cwd: Path = PROJECT_ROOT,
) -> dict[str, Any]:
    result = subprocess.run(
        arguments,
        cwd=cwd,
        env=environment,
        text=True,
        encoding="utf-8",
        errors="replace",
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=60,
        check=False,
    )
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip()
        raise RuntimeError(
            f"Codex rejected generated configuration (exit {result.returncode})"
            + (f": {detail}" if detail else ".")
        )
    try:
        document = json.loads(result.stdout)
    except json.JSONDecodeError as error:
        raise RuntimeError("Codex returned invalid JSON while validating its model catalog.") from error
    if not isinstance(document, dict):
        raise RuntimeError("Codex returned an unexpected model-catalog shape.")
    return document


def _bundled_template(codex_executable: str, environment: dict[str, str]) -> dict[str, Any]:
    document = _run_json(
        [codex_executable, "debug", "models", "--bundled"],
        environment=environment,
    )
    models = document.get("models")
    if not isinstance(models, list) or not models:
        raise RuntimeError("The installed Codex CLI provided no bundled model metadata.")
    template = next(
        (model for model in models if isinstance(model, dict) and model.get("slug") == "gpt-5.5"),
        None,
    )
    if template is None:
        template = next((model for model in models if isinstance(model, dict)), None)
    if template is None:
        raise RuntimeError("The bundled Codex model catalog had no usable model entry.")
    return copy.deepcopy(template)


def _model_entry(template: dict[str, Any], settings: ModelSettings) -> dict[str, Any]:
    reasoning_entries = [
        {
            "effort": level,
            "description": f"Use {level} reasoning effort on the selected Hugging Face model",
        }
        for level in settings.reasoning_levels
    ]
    instructions = str(template.get("base_instructions") or "")
    identity = (
        f"You are Codex, powered only by {settings.display_model} through a Modal endpoint."
    )
    if instructions:
        instructions = re.sub(r"\AYou are Codex,[^\r\n]*", identity, instructions)
    else:
        instructions = identity
    instructions += (
        "\n\nUse the standard tools supplied by Codex. Use the apply_patch tool for file edits."
    )

    template.update(
        {
            "slug": settings.slug,
            "display_name": f"Modal: {settings.display_model}",
            "description": "Hugging Face model served by a Modal managed endpoint",
            "default_reasoning_level": settings.reasoning_effort,
            "supported_reasoning_levels": reasoning_entries,
            "shell_type": "shell_command",
            "visibility": "list",
            "supported_in_api": True,
            "priority": 0,
            "base_instructions": instructions,
            "apply_patch_tool_type": "freeform",
            "supports_parallel_tool_calls": True,
            "supports_reasoning_summaries": True,
            "default_reasoning_summary": "none",
            "reasoning_summary_format": "none",
            "support_verbosity": False,
            "supports_search_tool": False,
            "supports_image_detail_original": False,
            "input_modalities": ["text"],
            "context_window": settings.context_window,
            "max_context_window": settings.context_window,
            "effective_context_window_percent": 95,
            "prefer_websockets": False,
            "use_responses_lite": False,
            "service_tiers": [],
            "additional_speed_tiers": [],
        }
    )
    for property_name in (
        "availability_nux",
        "upgrade",
        "minimal_client_version",
        "default_verbosity",
        "web_search_tool_type",
        "tool_mode",
        "available_in_plans",
        "comp_hash",
        "policy_template",
    ):
        template.pop(property_name, None)
    return template


